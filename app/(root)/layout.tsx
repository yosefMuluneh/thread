import type { Metadata } from "next";
import { Inter } from "next/font/google";
import "../globals.css";
import { ClerkProvider } from "@clerk/nextjs";
import { LeftSideBar } from "@/components/shared/LeftSideBar";
import TopBar from "@/components/shared/TopBar";
import RightSideBar from "@/components/shared/RightSideBar";
import BottomBar from "@/components/shared/BottomBar";
import { LikeStateProvider } from "@/components/providers/LikeStateProvider";
import { getUnreadNotificationCount } from "@/lib/actions/notification.actions";

export const dynamic = "force-dynamic";

const inter = Inter({ subsets: ["latin"] });

export const metadata: Metadata = {
  title: "Threads",
  description: "Generated by create next app",
};

export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  // RootLayout can also render for signed-out visitors. Keep the navigation
  // usable in that case and show a zero badge instead of throwing an error.
  let unreadCount = 0;

  try {
    unreadCount = await getUnreadNotificationCount();
  } catch {
    unreadCount = 0;
  }

  return (
    <ClerkProvider>
      <html lang="en">
        <body className={inter.className}>
          <LikeStateProvider>
            <TopBar />
            <main className="flex flex-row">
              <LeftSideBar unreadCount={unreadCount} />
              <section className="main-container">
                <div className="w-full max-w-4xl">{children}</div>
              </section>
              <RightSideBar />
            </main>
            <BottomBar unreadCount={unreadCount} />
          </LikeStateProvider>
        </body>
      </html>
    </ClerkProvider>
  );
}
